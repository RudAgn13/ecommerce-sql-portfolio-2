-- ============================================================
-- SCHEMA
-- ============================================================

DROP TABLE IF EXISTS returns          CASCADE;
DROP TABLE IF EXISTS payments         CASCADE;
DROP TABLE IF EXISTS order_items      CASCADE;
DROP TABLE IF EXISTS orders           CASCADE;
DROP TABLE IF EXISTS customer_sessions CASCADE;
DROP TABLE IF EXISTS marketing_events CASCADE;
DROP TABLE IF EXISTS products         CASCADE;
DROP TABLE IF EXISTS categories       CASCADE;
DROP TABLE IF EXISTS sellers          CASCADE;
DROP TABLE IF EXISTS customers        CASCADE;

CREATE TABLE customers (
    customer_id         SERIAL PRIMARY KEY,
    full_name           VARCHAR(100),
    email               VARCHAR(150) UNIQUE,
    city                VARCHAR(60),
    state               VARCHAR(60),
    tier                VARCHAR(20)  CHECK (tier IN ('bronze','silver','gold','platinum')),
    acquisition_channel VARCHAR(40),
    created_at          TIMESTAMP,
    last_login          TIMESTAMP,
    is_active           BOOLEAN DEFAULT TRUE
);

CREATE TABLE categories (
    category_id       SERIAL PRIMARY KEY,
    category_name     VARCHAR(100),
    parent_category   VARCHAR(100),
    commission_rate   NUMERIC(5,4)
);

CREATE TABLE sellers (
    seller_id           SERIAL PRIMARY KEY,
    seller_name         VARCHAR(150),
    city                VARCHAR(60),
    state               VARCHAR(60),
    onboarded_at        TIMESTAMP,
    seller_tier         VARCHAR(20) CHECK (seller_tier IN ('new','standard','preferred','elite')),
    avg_dispatch_days   NUMERIC(4,2),
    is_active           BOOLEAN DEFAULT TRUE
);

CREATE TABLE products (
    product_id      SERIAL PRIMARY KEY,
    product_name    VARCHAR(200),
    category_id     INT REFERENCES categories(category_id),
    seller_id       INT REFERENCES sellers(seller_id),
    brand           VARCHAR(100),
    cost_price      NUMERIC(10,2),
    mrp             NUMERIC(10,2),
    selling_price   NUMERIC(10,2),
    weight_kg       NUMERIC(6,3),
    is_perishable   BOOLEAN DEFAULT FALSE,
    launched_at     TIMESTAMP,
    is_active       BOOLEAN DEFAULT TRUE
);

CREATE TABLE customer_sessions (
    session_id      SERIAL PRIMARY KEY,
    customer_id     INT REFERENCES customers(customer_id),
    session_start   TIMESTAMP,
    session_end     TIMESTAMP,
    device_type     VARCHAR(20) CHECK (device_type IN ('mobile','desktop','tablet')),
    platform        VARCHAR(20) CHECK (platform IN ('android','ios','web')),
    utm_source      VARCHAR(60),
    utm_medium      VARCHAR(60),
    pages_viewed    INT,
    converted       BOOLEAN DEFAULT FALSE,
    bounce          BOOLEAN DEFAULT FALSE
);

CREATE TABLE orders (
    order_id            SERIAL PRIMARY KEY,
    customer_id         INT REFERENCES customers(customer_id),
    session_id          INT REFERENCES customer_sessions(session_id),
    order_date          TIMESTAMP,
    expected_delivery   DATE,
    actual_delivery     DATE,
    order_status        VARCHAR(30) CHECK (order_status IN (
                            'placed','confirmed','packed','shipped',
                            'delivered','cancelled','returned')),
    shipping_city       VARCHAR(60),
    shipping_state      VARCHAR(60),
    gross_amount        NUMERIC(12,2),
    discount_amount     NUMERIC(12,2),
    net_amount          NUMERIC(12,2),
    shipping_fee        NUMERIC(8,2),
    coupon_code         VARCHAR(30)
);

CREATE TABLE order_items (
    item_id         SERIAL PRIMARY KEY,
    order_id        INT REFERENCES orders(order_id),
    product_id      INT REFERENCES products(product_id),
    seller_id       INT REFERENCES sellers(seller_id),
    quantity        INT,
    unit_price      NUMERIC(10,2),
    discount_pct    NUMERIC(5,4),
    line_total      NUMERIC(12,2),
    is_returned     BOOLEAN DEFAULT FALSE
);

CREATE TABLE payments (
    payment_id      SERIAL PRIMARY KEY,
    order_id        INT REFERENCES orders(order_id),
    payment_method  VARCHAR(30) CHECK (payment_method IN (
                        'upi','credit_card','debit_card',
                        'net_banking','cod','wallet','bnpl')),
    payment_status  VARCHAR(20) CHECK (payment_status IN (
                        'success','failed','refunded','pending')),
    payment_gateway VARCHAR(40),
    amount          NUMERIC(12,2),
    initiated_at    TIMESTAMP,
    settled_at      TIMESTAMP,
    failure_reason  VARCHAR(100)
);

CREATE TABLE marketing_events (
    event_id        SERIAL PRIMARY KEY,
    customer_id     INT REFERENCES customers(customer_id),
    event_type      VARCHAR(40) CHECK (event_type IN (
                        'email_sent','email_opened','email_clicked',
                        'push_sent','push_clicked',
                        'sms_sent','sms_clicked',
                        'ad_impression','ad_clicked')),
    campaign_name   VARCHAR(100),
    channel         VARCHAR(30),
    utm_source      VARCHAR(60),
    utm_medium      VARCHAR(60),
    event_timestamp TIMESTAMP,
    cost_per_event  NUMERIC(8,4)
);

CREATE TABLE returns (
    return_id               SERIAL PRIMARY KEY,
    order_id                INT REFERENCES orders(order_id),
    item_id                 INT REFERENCES order_items(item_id),
    customer_id             INT REFERENCES customers(customer_id),
    return_reason           VARCHAR(80) CHECK (return_reason IN (
                                'damaged','wrong_item','quality_issue',
                                'size_mismatch','changed_mind','late_delivery','other')),
    return_requested_at     TIMESTAMP,
    return_resolved_at      TIMESTAMP,
    refund_amount           NUMERIC(12,2),
    refund_status           VARCHAR(20) CHECK (refund_status IN ('pending','processed','rejected')),
    seller_fault            BOOLEAN
);

